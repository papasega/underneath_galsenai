"""Build report/senegal.tex (TikZ map of Senegal with its 14 regions) from assets/senegal_adm1.geojson.

Data: geoBoundaries gbOpen SEN ADM1, simplified (CC BY 4.0, https://www.geoboundaries.org). Equirectangular projection
corrected by cos(14 deg), 2 cm per degree of latitude. The GalsenAI logo (assets/galsenai-blanc-sans-signature.svg,
converted to vector PDF as report/assets/galsenai_logo_blanc.pdf) sits in the middle of the country.
"""

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LON0, LAT0, K = -17.7, 12.2, 2.0
COS = math.cos(math.radians(14))
proj = lambda lon, lat: ((lon - LON0) * COS * K, (lat - LAT0) * K)

paths = []
for f in json.loads((ROOT / "assets/senegal_adm1.geojson").read_text())["features"]:
    g = f["geometry"]
    for poly in g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]:
        ring = poly[0]
        paths.append(" -- ".join("({:.2f},{:.2f})".format(*proj(x, y)) for x, y in ring[:: 1]) + " -- cycle")
cx, cy = proj(-14.3, 14.55)
body = "\n".join(f"  \\path[fill=white,fill opacity=0.09,draw=white,draw opacity=0.35,line width=0.3pt,line join=round] {p};" for p in paths)
(ROOT / "report/senegal.tex").write_text(
    "% Generated by scripts/make_senegal_map.py (geoBoundaries SEN ADM1, CC BY 4.0). Do not edit.\n"
    "\\newcommand{\\senegalmap}[1]{%\n\\begin{tikzpicture}[scale=#1]\n" + body +
    f"\n  \\node[inner sep=0] at ({cx:.2f},{cy:.2f}) {{\\includegraphics[width=4.6cm]{{galsenai_logo_blanc.pdf}}}};\n"
    "\\end{tikzpicture}}\n", encoding="utf-8")
print(len(paths), "polygons")
